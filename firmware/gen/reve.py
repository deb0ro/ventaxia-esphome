NTC_INTERVAL = '''  # NTCs (rev E): each on its own ADC1 input, 10k pull-up to 3.3 V, NTC to GND, 1k + 100n -> R = 10k V / (3.3 - V).
  # A reading counts as valid (t1_ok_ms / t2_ok_ms) only when R is plausible: 500 Ohm .. 150 kOhm (~+90 .. -40 C).
  # Open NTC -> ~3.3 V (above the ADC range), short -> 0 V: both rejected.
  - interval: ${ntc_interval}
    then:
      - component.update: ntc1_adc
      - component.update: ntc2_adc
      - delay: 100ms
      - lambda: |-
          const float vs = 3.3f, rp = 10000.0f;
          auto res = [vs, rp](float v) { return (std::isfinite(v) && v > 0.02f && v < vs - 0.05f) ? rp * v / (vs - v) : NAN; };
          const float r1 = res(id(ntc1_adc).state), r2 = res(id(ntc2_adc).state);
          const bool g1 = std::isfinite(r1) && r1 > 500.0f && r1 < 150000.0f;
          const bool g2 = std::isfinite(r2) && r2 > 500.0f && r2 < 150000.0f;
          if (g1) id(t1_ok_ms) = millis();
          if (g2) id(t2_ok_ms) = millis();
          id(ntc1_r).publish_state(g1 ? r1 : NAN);
          id(ntc2_r).publish_state(g2 ? r2 : NAN);
'''


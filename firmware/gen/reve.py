def transform(t):
    i = t.index('#\n# Settings storage')
    t = HEADER + t[i:]
    for a, b, n in PAIRS:
        assert t.count(a) == n, ('reve: %d x expected' % n, a[:80])
        t = t.replace(a, b)
    a = t.index('  # Read the two NTCs through the single ADC.')
    b = t.index('          id(ntc2_r).publish_state(g2 ? r2 : NAN);\n') + len('          id(ntc2_r).publish_state(g2 ? r2 : NAN);\n')
    t = t[:a] + NTC_INTERVAL + t[b:]
    a = t.index('  # --- NTC readout: one ADC')
    end = '          else if (id(ntc_active) == 2) id(ntc_vb) = x;\n'
    b = t.index(end) + len(end)
    t = t[:a] + ADC + t[b:]
    end = '''  - platform: wifi_signal
    name: "WiFi signal"
    update_interval: 60s
'''
    assert t.endswith(end), 'reve: template must end with the wifi_signal sensor'
    t = t + SENSORS
    for bad in ('esp8266_pwm', 'nodemcu', 'GPIO14', 'GPIO13', 'GPIO12', 'ntc_active', 'pinMode', 'digitalWrite', 'A0\n'):
        assert bad not in t, ('reve: alpha hardware left', bad)
    assert t.count('inverted: true') == 1, 'reve: only the LS input may be inverted (PWM is NON-inverted on rev E)'
    return t
